export function translate(value: string): string {
  if (language === "ar") return value;
  const key = value.replace(/\s+/g, " ").trim();
  if (english[key]) return `${/^\s/.test(value) ? " " : ""}${english[key]}${/\s$/.test(value) ? " " : ""}`;
  if (/^تأخير (\d+) دقيقة عن بدء العمل$/.test(key)) return key.replace(/^تأخير (\d+) .*$/, "$1 min late to start");
  if (/^عمل (\d+) دقيقة بعد نهاية الدوام$/.test(key)) return key.replace(/^عمل (\d+) .*$/, "Worked $1 min after hours");
  if (/^(\d+) معتمد · (.+) في الموعد$/.test(key)) return key.replace(/^(\d+) معتمد · (.+) في الموعد$/, "$1 approved · $2 on time");
  if (/^(\d+) أُرسل · (\d+) مراجعة$/.test(key)) return key.replace(/^(\d+) أُرسل · (\d+) مراجعة$/, "$1 sent · $2 reviews");
  if (/^(\d+) موظف$/.test(key)) return key.replace(/^(\d+) موظف$/, "$1 staff");
  if (/^تأخير (\d+) دقيقة$/.test(key)) return key.replace(/^تأخير (\d+) دقيقة$/, "$1 min late");
  if (/^تأخير (\d+) د$/.test(key)) return key.replace(/^تأخير (\d+) د$/, "$1 min late");
  if (/^مدفوع (.+)$/.test(key)) return key.replace(/^مدفوع (.+)$/, "Paid $1");
  if (/^(\d+) طلب بانتظار مراجعتك$/.test(key)) return key.replace(/^(\d+) .*$/, "$1 requests awaiting your review");
  if (/^(\d+) رد جديد من الإدارة العليا$/.test(key)) return key.replace(/^(\d+) .*$/, "$1 new replies from head office");
  if (/^حضرت (.+) — في الموعد$/.test(key)) return key.replace(/^حضرت (.+) — في الموعد$/, "Arrived $1 — on time");
  if (/^حضرت (.+) — تأخير (\d+) دقيقة$/.test(key)) return key.replace(/^حضرت (.+) — تأخير (\d+) دقيقة$/, "Arrived $1 — $2 min late");
  if (/^(\d+) سلبي · (\d+) ملغي$/.test(key)) return key.replace(/^(\d+) سلبي · (\d+) ملغي$/, "$1 negative · $2 cancelled");
  if (/^(\S+) د$/.test(key)) return key.replace(/^(\S+) د$/, "$1 min");
  if (/^(\S+) ث$/.test(key)) return key.replace(/^(\S+) ث$/, "$1 s");
  if (/^(\S+) س( (\S+) د)?$/.test(key)) return key.replace(/^(\S+) س( (\S+) د)?$/, (_m, h, _r, m) => `${h} h${m ? ` ${m} min` : ""}`);
  if (/^(\S+) ي( (\S+) س)?$/.test(key)) return key.replace(/^(\S+) ي( (\S+) س)?$/, (_m, d, _r, h) => `${d} d${h ? ` ${h} h` : ""}`);
  if (key.startsWith("بعد ")) return `after ${translate(key.slice(4))}`;
  if (/^(.+) نقطة$/.test(key)) return key.replace(/ نقطة$/, " points");
  if (/^(.+) تقرير$/.test(key)) return key.replace(/ تقرير$/, " reports");
  if (/^(\d+) استعلام معتمد$/.test(key)) return key.replace(/^(\d+) .*$/, "$1 approved");
  if (/^هامش (.+)٪$/.test(key)) return key.replace(/^هامش (.+)٪$/, "$1% margin");
  if (/^(\d+) استعلام لم يُعتمد بعد$/.test(key)) return key.replace(/^(\d+) .*$/, "$1 not yet approved");
  if (key === "قيد التنفيذ") return "In progress";
  if (key.startsWith("أرباح ")) return key.replace(/^أرباح /, "Earnings ");
  if (key.startsWith("بانتظار الاعتماد ")) return key.replace("بانتظار الاعتماد", "Pending approval");
  if (/^(\d+) معتمد · (\d+) قيد العمل$/.test(key)) return key.replace(/^(\d+) معتمد · (\d+) قيد العمل$/, "$1 approved · $2 active");
  if (/^(\d+) متأخر الآن$/.test(key)) return key.replace(/^(\d+) .*$/, "$1 overdue now");
  if (/^(\d+) ساعة$/.test(key)) return key.replace(/^(\d+) ساعة$/, "$1 hours");
  if (key.startsWith("معدل ")) return key.replace(/^معدل /, "Rate ");
  if (/^(\d+) ملغي$/.test(key)) return key.replace(/^(\d+) .*$/, "$1 cancelled");
  if (/^(\d+) تقرير معتمد$/.test(key)) return key.replace(/^(\d+) .*$/, "$1 approved reports");
  if (/^(\d+) · (\d+) نشط$/.test(key)) return key.replace(/^(\d+) · (\d+) نشط$/, "$1 · $2 active");
  if (/^(\d+) مستعلم في هذه المنطقة$/.test(key)) return key.replace(/^(\d+) .*$/, "$1 investigators in this area");
  if (/^(\d+) مستعلم في المنطقة المحددة$/.test(key)) return key.replace(/^(\d+) .*$/, "$1 investigators in the selected area");
  if (/^(\d+) في المنطقة$/.test(key)) return key.replace(/^(\d+) .*$/, "$1 in area");
  if (key.startsWith("نوع الاستعلام — ")) return key.replace("نوع الاستعلام", "Investigation type");
  if (key.startsWith("نصف القطر:")) return key.replace("نصف القطر:", "Radius:").replace("كم", "km");
  if (key.startsWith("المستعلم: ")) return key.replace("المستعلم:", "Investigator:");
  if (key.startsWith("ملاحظة المراجع: ")) return key.replace("ملاحظة المراجع:", "Reviewer note:");
  if (/^\d+ متبقية$/.test(key)) return key.replace("متبقية", "remaining");
  if (/^الصفحة (.+) من (.+)$/.test(key)) return key.replace(/^الصفحة (.+) من (.+)$/, "Page $1 of $2");
  if (key.startsWith("عرض ")) return key.replace(/^عرض /, "View ");
  if (key.startsWith("إدارة حسابي —")) return key.replace("إدارة حسابي", "My account");
  if (/^لديك (\d+) طلبات بانتظار المراجعة\.$/.test(key)) return key.replace(/^لديك (\d+) طلبات بانتظار المراجعة\.$/, "$1 applications awaiting review.");
  if (key.startsWith("أرسلنا رمز تحقق إلى ")) {
    const recipient = key.slice("أرسلنا رمز تحقق إلى ".length).split(". ")[0];
    return `We sent a verification code to ${recipient}. Enter the six-digit code to continue. Check your spam folder too.`;
  }
  if (key.startsWith("هل تريد ") && key.includes("المصادقة بخطوتين")) return `Do you want to ${key.includes("disable") || key.includes("تعطيل") ? "disable" : "enable"} two-step verification? Current sessions will end.`;
  if (key.startsWith("الحسابات:")) return key.replace("الحسابات:", "Accounts:").replace("نشطة،", "active,").replace("معلّقة،", "pending,").replace("أخرى", "other");
  return value;
}
